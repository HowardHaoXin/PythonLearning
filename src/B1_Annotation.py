# 注释的理解与使用
# 1.单行注释(最常用)
# 1.1 作用：给一行代码做说明，或临时禁用某一行代码
# 1.2 语法：以#开头，后续写注释内容
# 1.3 两种写法：
# 第一种：注释单独一行（常用）
# 输出123
print(123)
# 第二种：注释跟在代码后
print(123)  # 输出123

# 2.多行注释
# 2.1 作用：给一段代码、一个功能（如函数、类）或整个文件做说明，或临时禁用多行代码
# 2.2 语法：以'''开头，以'''结尾。如：
'''
第一种：
注释内容
'''
'''第二种：注释内容'''

# 3.快速注释
# 3.1 快捷键：Ctrl + /